-- 1. ТАБЛИЦЫ СПРАВОЧНИКОВ И СУЩНОСТЕЙ
-- ============================================================================

-- 1.1 Справочник ролей пользователей (Лаборант, Энергетик, ИТ-админ, Администратор)
CREATE TABLE roles (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code VARCHAR(32) NOT NULL UNIQUE,
    role_name VARCHAR(80) NOT NULL,
    permissions_json JSONB NOT NULL DEFAULT '{}'::jsonb
);

-- 1.2 Пользователи системы
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id SMALLINT NOT NULL REFERENCES roles(role_id) ON DELETE RESTRICT,
    login VARCHAR(60) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    position_title VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 1.3 Учебные аудитории и компьютерные классы корпуса А (201, 202, 204, 301, 302, 305)
CREATE TABLE rooms (
    room_id VARCHAR(16) PRIMARY KEY,
    building_code VARCHAR(16) NOT NULL DEFAULT 'A',
    floor_num SMALLINT NOT NULL CHECK (floor_num BETWEEN 1 AND 12),
    room_name VARCHAR(100) NOT NULL,
    room_type VARCHAR(60) NOT NULL,
    total_pcs INTEGER NOT NULL CHECK (total_pcs >= 0),
    light_line_watts INTEGER NOT NULL DEFAULT 120 CHECK (light_line_watts >= 0),
    current_state VARCHAR(16) NOT NULL DEFAULT 'S2_IDLE'
        CHECK (current_state IN ('S1_OCCUPIED', 'S2_IDLE', 'S3_EXCESS', 'S0_OFFLINE'))
);

-- 1.4 Узловые контроллеры сбора телеметрии ESP32
CREATE TABLE room_controllers (
    controller_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id VARCHAR(16) NOT NULL UNIQUE REFERENCES rooms(room_id) ON DELETE CASCADE,
    mac_address VARCHAR(24) NOT NULL UNIQUE,
    ip_address VARCHAR(45) NULL,
    firmware_ver VARCHAR(32) NOT NULL DEFAULT 'v1.2.0-esp32',
    is_online BOOLEAN NOT NULL DEFAULT TRUE,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 1.5 Поштучный реестр рабочих станций ПК и электроприёмников (72 ПК в корпусе А)
CREATE TABLE workstations_devices (
    device_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id VARCHAR(16) NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
    device_code VARCHAR(24) NOT NULL,
    device_type VARCHAR(24) NOT NULL DEFAULT 'PC'
        CHECK (device_type IN ('PC', 'LIGHT', 'HVAC', 'SWITCH')),
    rated_watts INTEGER NOT NULL DEFAULT 150 CHECK (rated_watts > 0),
    is_power_on BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_room_device_code UNIQUE (room_id, device_code)
);

-- 1.6 Академическое расписание учебных занятий (фактор занятости x4)
CREATE TABLE schedule_slots (
    slot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id VARCHAR(16) NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    pair_number SMALLINT NOT NULL CHECK (pair_number BETWEEN 1 AND 8),
    time_start TIME NOT NULL,
    time_end TIME NOT NULL,
    group_code VARCHAR(40) NOT NULL,
    subject_name VARCHAR(120) NOT NULL,
    teacher_name VARCHAR(120) NULL,
    CONSTRAINT chk_schedule_time CHECK (time_end > time_start)
);

-- 1.7 Версионный справочник уставок мощности, температурных порогов и тарифа (x2, x3, x5)
CREATE TABLE system_settings_tariffs (
    setting_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pc_watts INTEGER NOT NULL DEFAULT 150 CHECK (pc_watts BETWEEN 30 AND 1000),
    light_watts INTEGER NOT NULL DEFAULT 120 CHECK (light_watts BETWEEN 10 AND 2000),
    min_temp_c NUMERIC(4,1) NOT NULL DEFAULT 18.0 CHECK (min_temp_c BETWEEN 10.0 AND 25.0),
    max_temp_c NUMERIC(4,1) NOT NULL DEFAULT 26.0 CHECK (max_temp_c BETWEEN 18.0 AND 35.0),
    tariff_kzt_kwh NUMERIC(8,2) NOT NULL DEFAULT 32.50 CHECK (tariff_kzt_kwh > 0),
    valid_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_temp_bounds CHECK (max_temp_c > min_temp_c)
);

-- 1.8 Временной ряд первичных замеров телеметрии (входные факторы x1..x7)
CREATE TABLE telemetry_measurements (
    measurement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id VARCHAR(16) NOT NULL REFERENCES rooms(room_id) ON DELETE RESTRICT,
    controller_id BIGINT NOT NULL REFERENCES room_controllers(controller_id) ON DELETE RESTRICT,
    measured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_online BOOLEAN NOT NULL DEFAULT TRUE,
    is_occupied BOOLEAN NOT NULL DEFAULT FALSE,
    active_pcs INTEGER NOT NULL CHECK (active_pcs >= 0),
    total_pcs INTEGER NOT NULL CHECK (total_pcs >= 0),
    light_on BOOLEAN NOT NULL DEFAULT FALSE,
    pc_watts_snapshot INTEGER NOT NULL CHECK (pc_watts_snapshot > 0),
    light_watts_snapshot INTEGER NOT NULL CHECK (light_watts_snapshot >= 0),
    tariff_kzt_snapshot NUMERIC(8,2) NOT NULL CHECK (tariff_kzt_snapshot > 0),
    temp_c NUMERIC(4,1) NOT NULL CHECK (temp_c BETWEEN -10.0 AND 55.0),
    open_windows SMALLINT NOT NULL DEFAULT 0 CHECK (open_windows >= 0),
    door_open BOOLEAN NOT NULL DEFAULT FALSE,
    calc_power_kw NUMERIC(6,2) NOT NULL CHECK (calc_power_kw >= 0),
    CONSTRAINT chk_active_pcs_limit CHECK (active_pcs <= total_pcs)
);

-- 1.9 Реестр версий моделей искусственного интеллекта
CREATE TABLE ml_models (
    model_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name VARCHAR(80) NOT NULL,
    version_tag VARCHAR(40) NOT NULL UNIQUE,
    algorithm_type VARCHAR(60) NOT NULL,
    artifact_uri TEXT NULL,
    confidence_threshold NUMERIC(4,2) NOT NULL DEFAULT 0.75 CHECK (confidence_threshold BETWEEN 0.00 AND 1.00),
    metrics_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    trained_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- 1.10 Журнал запусков интеллектуального оценивания E = f(X)
CREATE TABLE ai_evaluation_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id VARCHAR(16) NOT NULL REFERENCES rooms(room_id) ON DELETE RESTRICT,
    measurement_id BIGINT NOT NULL REFERENCES telemetry_measurements(measurement_id) ON DELETE CASCADE,
    model_id BIGINT NOT NULL REFERENCES ml_models(model_id) ON DELETE RESTRICT,
    setting_id BIGINT NOT NULL REFERENCES system_settings_tariffs(setting_id) ON DELETE RESTRICT,
    derived_features JSONB NOT NULL DEFAULT '{}'::jsonb,
    state_class VARCHAR(16) NOT NULL
        CHECK (state_class IN ('S1_OCCUPIED', 'S2_IDLE', 'S3_EXCESS', 'S0_OFFLINE')),
    current_power_kw NUMERIC(6,2) NOT NULL CHECK (current_power_kw >= 0),
    baseline_forecast_kw NUMERIC(6,2) NOT NULL CHECK (baseline_forecast_kw >= 0),
    saving_kwh_1h NUMERIC(6,2) NOT NULL DEFAULT 0.00 CHECK (saving_kwh_1h >= 0),
    saving_kwh_4h NUMERIC(7,2) NOT NULL DEFAULT 0.00 CHECK (saving_kwh_4h >= 0),
    saving_kzt_4h NUMERIC(10,2) NOT NULL DEFAULT 0.00 CHECK (saving_kzt_4h >= 0),
    confidence_score NUMERIC(4,2) NOT NULL DEFAULT 1.00 CHECK (confidence_score BETWEEN 0.00 AND 1.00),
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 1.11 Суточные и недельные прогнозы электропотребления
CREATE TABLE energy_forecasts (
    forecast_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id VARCHAR(16) NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
    model_id BIGINT NOT NULL REFERENCES ml_models(model_id) ON DELETE RESTRICT,
    horizon_type VARCHAR(16) NOT NULL CHECK (horizon_type IN ('day_24h', 'week_7d')),
    target_timestamp TIMESTAMPTZ NOT NULL,
    predicted_kw NUMERIC(6,2) NOT NULL CHECK (predicted_kw >= 0),
    baseline_no_ctrl_kw NUMERIC(6,2) NOT NULL CHECK (baseline_no_ctrl_kw >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 1.12 Обнаруженные аномалии энергопотребления, микроклимата и связи с векторами XAI
CREATE TABLE detected_anomalies (
    anomaly_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES ai_evaluation_runs(run_id) ON DELETE CASCADE,
    room_id VARCHAR(16) NOT NULL REFERENCES rooms(room_id) ON DELETE RESTRICT,
    anomaly_type VARCHAR(24) NOT NULL
        CHECK (anomaly_type IN ('energy', 'climate', 'window', 'offline')),
    severity VARCHAR(16) NOT NULL DEFAULT 'warning'
        CHECK (severity IN ('warning', 'neutral', 'critical')),
    title VARCHAR(160) NOT NULL,
    explanation_text TEXT NOT NULL,
    xai_factors JSONB NOT NULL DEFAULT '[]'::jsonb,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 1.13 Управленческие рекомендации лаборанту с жизненным циклом (BP-10 / BP-11)
CREATE TABLE saving_recommendations (
    recommendation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anomaly_id BIGINT NOT NULL REFERENCES detected_anomalies(anomaly_id) ON DELETE CASCADE,
    room_id VARCHAR(16) NOT NULL REFERENCES rooms(room_id) ON DELETE RESTRICT,
    assigned_user_id BIGINT NULL REFERENCES users(user_id) ON DELETE SET NULL,
    action_text TEXT NOT NULL,
    expected_saving_kwh NUMERIC(7,2) NOT NULL DEFAULT 0.00 CHECK (expected_saving_kwh >= 0),
    expected_saving_kzt NUMERIC(10,2) NOT NULL DEFAULT 0.00 CHECK (expected_saving_kzt >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'new'
        CHECK (status IN ('new', 'accepted', 'completed', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ NULL,
    operator_comment TEXT NULL,
    CONSTRAINT chk_processed_time CHECK (
        (status = 'new' AND processed_at IS NULL)
        OR (status IN ('accepted', 'completed', 'rejected') AND processed_at IS NOT NULL)
    )
);

-- 1.14 Сквозной журнал системных событий
CREATE TABLE system_events_log (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id VARCHAR(16) NULL REFERENCES rooms(room_id) ON DELETE SET NULL,
    user_id BIGINT NULL REFERENCES users(user_id) ON DELETE SET NULL,
    run_id BIGINT NULL REFERENCES ai_evaluation_runs(run_id) ON DELETE SET NULL,
    event_type VARCHAR(24) NOT NULL
        CHECK (event_type IN ('energy', 'climate', 'window', 'offline', 'ok', 'settings', 'report_export')),
    event_text TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Индексы для ускорения выборок
CREATE INDEX idx_telemetry_room_time ON telemetry_measurements (room_id, measured_at DESC);
CREATE INDEX idx_runs_room_time ON ai_evaluation_runs (room_id, evaluated_at DESC);
CREATE INDEX idx_forecasts_room_target ON energy_forecasts (room_id, horizon_type, target_timestamp);
CREATE INDEX idx_anomalies_room_time ON detected_anomalies (room_id, detected_at DESC);
CREATE INDEX idx_recommendations_status ON saving_recommendations (status, created_at DESC);
CREATE INDEX idx_events_created_at ON system_events_log (created_at DESC);

